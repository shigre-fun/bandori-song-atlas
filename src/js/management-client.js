import { siteURL } from "./urls.js";

export function managementRoot() {
  const root = document.querySelector('meta[name="management-root"]')?.content;
  if (!root?.startsWith("/") || root.startsWith("//"))
    throw new Error("管理ページの設定を確認してください。");
  return root;
}
export const managementConfigURL = () => managementRoot() + "config.json";

// Copy only known draft fields. Never migrate tokens, and never overwrite an existing new draft.
export function migrateManagementDrafts(storage, root, legacyRoot) {
  const keys = [
    ["garupa-song-draft-v1:", ""],
    ["song-draft-v2:", ":ournotes"],
  ];
  const errors = [];
  for (const [prefix, suffix] of keys) {
    const oldKey = prefix + legacyRoot + suffix,
      newKey = prefix + root + suffix;
    for (const repository of [false, true]) {
      const from = oldKey + (repository ? ":repository" : "");
      const to = newKey + (repository ? ":repository" : "");
      try {
        if (storage.getItem(to) !== null || storage.getItem(from) === null)
          continue;
        const old = JSON.parse(storage.getItem(from));
        const clean = repository
          ? Object.fromEntries(
              ["owner", "repo", "branch"]
                .filter((k) => typeof old?.[k] === "string")
                .map((k) => [k, old[k]]),
            )
          : Object.fromEntries(
              ["values", "editing", "submissionId", "savedResult"]
                .filter((k) => old?.[k] !== undefined)
                .map((k) => [k, old[k]]),
            );
        // Legacy drafts are generated by draftValues(), which excludes the connection form.
        if (clean.values)
          clean.values = Object.fromEntries(
            Object.entries(clean.values).filter(
              ([k]) => !/token|password|secret/i.test(k),
            ),
          );
        storage.setItem(to, JSON.stringify(clean));
      } catch {
        errors.push(from);
      }
    }
  }
  return errors.length === 0;
}

export function restoreLegacyManagementDrafts() {
  try {
    return migrateManagementDrafts(
      localStorage,
      managementRoot(),
      siteURL("admin/"),
    );
  } catch {
    return false;
  }
}
